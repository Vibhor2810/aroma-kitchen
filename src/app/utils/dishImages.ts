/**
 * Strict Multi-Tier Image Matcher:
 * Prevents curry/thali/biryani cross-contamination.
 */
export function resolveDishImage(
  sheetImageUrl: string | undefined,
  itemName: string,
  categoryName: string
): string {
  // 1. Google Sheets direct image (highest priority)
  if (sheetImageUrl && sheetImageUrl.trim().startsWith("http")) {
    return sheetImageUrl.trim();
  }

  const cleanItem = itemName.toLowerCase().trim();
  const cleanCat = categoryName.toLowerCase().trim();

  // 2. Direct exact match
  if (APPROVED_DISH_IMAGES[cleanItem]) {
    return APPROVED_DISH_IMAGES[cleanItem];
  }

  // 3. Strict Boundary Guards
  const isCurry = cleanItem.includes("curry") || cleanItem.includes("masala") || cleanItem.includes("kadhai") || cleanItem.includes("handi");
  const isThali = cleanItem.includes("thali");
  const isBiryani = cleanItem.includes("biryani") || cleanItem.includes("rice");

  // Sort keys by length so multi-word titles take precedence over broad words
  const sortedKeys = Object.keys(APPROVED_DISH_IMAGES).sort((a, b) => b.length - a.length);

  for (const key of sortedKeys) {
    // Curries must never match thalis or biryanis
    if (isCurry && (key.includes("thali") || key.includes("biryani") || key.includes("rice"))) {
      continue;
    }
    // Thalis must never match single curries
    if (isThali && !key.includes("thali")) {
      continue;
    }
    // Biryanis must not match curries
    if (isBiryani && !key.includes("biryani") && !key.includes("rice")) {
      continue;
    }

    if (cleanItem.includes(key)) {
      return APPROVED_DISH_IMAGES[key];
    }
  }

  // 4. Keyword Fallback from Dish Name
  for (const [catKey, url] of Object.entries(CATEGORY_FALLBACKS)) {
    if (cleanItem.includes(catKey)) {
      if (isCurry && catKey === "thali") continue;
      return url;
    }
  }

  // 5. Fallback from Sheet Category
  for (const [catKey, url] of Object.entries(CATEGORY_FALLBACKS)) {
    if (cleanCat.includes(catKey)) {
      if (isCurry && catKey === "thali") continue;
      return url;
    }
  }

  return CATEGORY_FALLBACKS.default;
}